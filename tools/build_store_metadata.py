"""Verifies the App Store copy in docs/store/listing/*.txt and writes docs/store/metadata.md from it.

The .txt files are the single source of truth (paste them into App Store Connect as they are). This script fails
(non-zero exit) if a limit or a rule is broken, so the numbers in metadata.md are always computed, never typed.

Run: python tools/build_store_metadata.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "docs/store/listing"
OUT = ROOT / "docs/store/metadata.md"

LIMITS = {"name": 30, "subtitle": 30, "promo": 170, "keywords": 100, "description": 4000, "whats-new": 4000, "review-notes": 4000}
REQUIRED_KEYWORDS = ["colour", "balayage", "blonde", "brunette", "redhead"]
COMPETITORS = ["youcam", "perfect corp", "perfect365", "faceapp", "facetune", "meitu", "loreal", "l'oreal", "garnier",
               "wella", "schwarzkopf", "revlon", "clairol", "snapchat", "instagram", "tiktok", "picsart", "vsco", "capcut"]
# Product scope: colour only. These words must not appear in the keyword field, name, subtitle or promo text.
SCOPE_WORDS = ["hairstyle", "hairstyles", "haircut", "haircuts", "bangs", "wig", "wigs"]
STOP = {"a", "an", "the", "and", "or", "of", "to", "in", "on", "for", "with"}

BASE = "https://ecomswiftllc.github.io/lustra/"
FALLBACK_NAMES = ["Hair Color Changer & Try-On", "Hair Dye Color Changer", "Hair Color Try On: Lustra"]


def read(n):
    return (LIST / f"{n}.txt").read_text(encoding="utf-8").strip("\r\n")


def words(s):
    return {w for w in re.findall(r"[a-z0-9]+", s.lower()) if w not in STOP}


def stem(w):
    return w[:-1] if w.endswith("s") and len(w) > 3 else w


def main():
    t = {k: read(k) for k in LIMITS}
    errs = []
    for k, lim in LIMITS.items():
        if len(t[k]) > lim:
            errs.append(f"{k}: {len(t[k])} > {lim}")
    if not t["name"].lower().endswith(": lustra") or t["name"].count(":") != 1:
        errs.append("name: keywords first, brand last, one colon (Hair Color Changer: Lustra)")
    if ":" in t["subtitle"]:
        errs.append("subtitle: keywords only, no colon")
    kw = t["keywords"]
    if " " in kw or kw.endswith(",") or kw.startswith(","):
        errs.append("keywords: no spaces, no stray commas")
    kwl = kw.split(",")
    if len(set(kwl)) != len(kwl):
        errs.append("keywords: repeated keyword")
    for r in REQUIRED_KEYWORDS:
        if r not in kwl:
            errs.append(f"keywords: missing {r}")
    seen = {stem(w) for w in words(t["name"] + " " + t["subtitle"])}
    for w in kwl:
        for part in w.split():
            if stem(part) in seen:
                errs.append(f"keywords: '{part}' already in name or subtitle")
    stems = [stem(w) for w in kwl]
    if len(set(stems)) != len(stems):
        errs.append("keywords: two keywords share a stem")
    blob = " ".join(t.values()).lower()
    for c in COMPETITORS:
        if re.search(rf"\b{re.escape(c)}\b", blob):
            errs.append(f"competitor or third-party brand named: {c}")
    scope_blob = " ".join(t[k] for k in ("name", "subtitle", "keywords", "promo", "whats-new")).lower()
    for w in SCOPE_WORDS:
        if re.search(rf"\b{w}\b", scope_blob):
            errs.append(f"out-of-scope feature word in name/subtitle/keywords/promo/whats-new: {w}")
    # the description may only mention them to say the app does NOT do them
    for m in re.finditer(r"[^\n]*\b(" + "|".join(SCOPE_WORDS) + r")\b[^\n]*", t["description"], flags=re.I):
        if "does not offer" not in m.group(0).lower():
            errs.append("description mentions an out-of-scope feature without saying it is not offered: " + m.group(0)[:60])
    if re.search(r"\bAI\b", " ".join(t.values())) or "artificial intelligence" in blob:
        errs.append("'AI' wording is not allowed (say on-device hair detection)")
    for bad in ["best ", "#1", "number one", "award", "5-star", "five star", "guaranteed", "salon-quality", "perfect result"]:
        if bad in blob:
            errs.append(f"unprovable claim wording: {bad.strip()}")
    if errs:
        print("STORE COPY CHECK FAILED")
        for e in errs:
            print(" -", e)
        sys.exit(1)

    def n(k):
        return f"{len(t[k])} of {LIMITS[k]}"

    md = f"""# Lustra: App Store listing (en-US)

Generated by `python tools/build_store_metadata.py` from `docs/store/listing/*.txt`. Edit those files, not this one.
Naming rule (owner, always): search keywords first, brand last, one colon. The check script enforced every number below.

| Field | Value | Characters |
|---|---|---|
| Name | {t['name']} | {n('name')} |
| Subtitle | {t['subtitle']} | {n('subtitle')} |
| Home screen name | Lustra | short on purpose, long names truncate |
| Promotional text | see below | {n('promo')} |
| Keywords | {t['keywords']} | {n('keywords')} |
| Description | see below | {n('description')} |
| What's New (1.0) | see below | {n('whats-new')} |
| Primary category | Photo & Video | |
| Secondary category | Lifestyle | |
| Price | Free, ads (AdMob banner on Home + opt-in rewarded ad before each export) | |
| Bundle id | com.ecomswift.lustra | |
| Copyright | 2026 Ecom Swift LLC | |
| Support URL | {BASE}support/ | |
| Marketing URL | {BASE} | |
| Privacy Policy URL | {BASE}privacy/ | |
| Terms of Use | {BASE}terms/ (add as a link in the description area or EULA field if wanted; Apple's standard EULA applies by default) | |
| Platforms | iPhone and iPad (universal), iOS 17.0 or later | |

Fallback names if Apple says "{t['name']}" is taken: {'; '.join(f'"{x}" ({len(x)})' for x in FALLBACK_NAMES)}. Keep the keywords-first, brand-last pattern.

Keyword field rules, checked by code: no word repeated from the name or subtitle (hair, color, changer, try, dye, ombre,
highlights), no spaces after commas, no repeated stem, no other app's or hair brand's name, none of hairstyle / haircut / bangs / wig
(the app is colour only). `colour` is the British spelling of a name word and a separate search term. Combinations
such as "hair colour" or "hair balayage" are formed by Apple from the name plus these single words.

## Promotional text ({n('promo')})

```
{t['promo']}
```

## Description ({n('description')})

Honest wording: no star or review claims, no competitor names, no "AI", no hairstyle or haircut claim, and the ad model stated plainly.

```
{t['description']}
```

Facts behind the wording (re-verify against docs/PRODUCT-SPEC.md and the shipped build before every submission, and edit the copy if a feature was cut):
hair colour try-on with natural shades, fashion colours and a custom colour; styles solid, ombre, balayage, highlights, two-tone and root
shadow; intensity, shine and brightness sliders; gray cover; gradient tool; refine brush; smooth/frizz soften and strand definition on the hair
only; before and after slider; undo and redo; detection hints (blurry, hat or covered hair, several faces, no face, small face, low light);
multi-face choice; palette compare grid (one export); saved looks on the device; hair detection on the device. Rewarded ad per export (a grid
counts as one). Free, no IAP, no account.

## What's New, version 1.0 ({n('whats-new')})

```
{t['whats-new']}
```

## App Review notes ({n('review-notes')})

```
{t['review-notes']}
```

Contact for review (App Store Connect form): the owner's name, phone and the support address. Sign-in required: No (do not tick it, no demo account).

## Age rating answers (Apple's questionnaire)

Expected result: 4+.

- In-app controls: Parental Controls No. Age Assurance No.
- Unrestricted Web Access: No. (The app does not embed a browser. Ads can open a website in Apple's system browser sheet, which is normal for ad SDKs.)
- User-Generated Content: No. Messaging and Chat: No. Advertising: Yes (Google AdMob, banner and rewarded video).
- Content descriptors, all None: Cartoon or Fantasy Violence, Realistic Violence, Prolonged Graphic or Sadistic Violence, Profanity or Crude Humor, Mature or Suggestive Themes, Horror or Fear Themes, Medical or Treatment Information, Alcohol Tobacco or Drug Use or References, Simulated Gambling, Sexual Content or Nudity, Contests, Gambling.
- Health or Wellness Topics: No.
- In AdMob set the maximum ad content rating to General (or Parental Guidance) and block sensitive categories, so the ads match the 4+ rating.

## App Privacy (nutrition label)

See `docs/store/app-privacy.md`. Summary: tracking Yes (Device ID, Advertising Data); Product Interaction and Performance Data collected and linked, not used for tracking; Coarse Location and Crash Data not linked. No photos are collected.

## Export compliance and other forms

- Encryption: the app uses only HTTPS through system and SDK networking (exempt): "uses standard encryption" and exempt. `ITSAppUsesNonExemptEncryption` should be set in Info.plist (check before upload).
- Content rights: the bundled sample photos come from Pexels under the Pexels License (`docs/store/photo-credits.md`). Answer Yes to "contains third-party content" with the right to use it. The MediaPipe hair segmenter model is Apache-2.0 (`docs/licences/hair-segmenter.md`).
- Digital Services Act trader status: Ecom Swift LLC as a trader, using the address and phone on the owner's Apple account.
- Sign in required: No.

## Screenshots

`python tools/make_store_shots.py <CI screenshots> design/store/6.9` (6.9-inch, 1320 x 2868) and
`python tools/make_store_shots_ipad.py <CI screenshots-ipad> design/store/ipad13` (13-inch iPad, 2064 x 2752).
Slides use real captures only; missing captures are skipped. Slide copy is in `tools/store_shots_common.py`.
Use only the bundled hair-from-behind samples in screenshots (nobody identifiable).

## Localisation

Later, same pattern in each language: translated keywords first, then ": Lustra" (es, fr, de, zh-Hans first).
"""
    OUT.write_text(md, encoding="utf-8", newline="\n")
    print("store copy OK")
    for k in LIMITS:
        print(f"  {k}: {len(t[k])}/{LIMITS[k]}")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
